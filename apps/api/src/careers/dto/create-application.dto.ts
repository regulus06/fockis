
import {
  IsArray,
  IsBoolean,
  IsDateString,
  IsEmail,
  IsObject,
  IsOptional,
  IsString,
  IsUrl,
  Length,
  MaxLength,
  ValidateNested,
  ArrayMaxSize,
  IsNotEmpty,
  Matches,
  IsNumber,
} from "class-validator";

import { Type } from "class-transformer";

/**
 * EDUCATION
 */
class EducationDto {
  @IsString()
  @IsNotEmpty()
  @MaxLength(200)
  school!: string;

  @IsString()
  @IsNotEmpty()
  @MaxLength(150)
  major!: string;

  @IsString()
  @IsNotEmpty()
  @MaxLength(50)
  graduationDate!: string;
}

/**
 * EXPERIENCE
 */
class ExperienceDto {
  @IsString()
  @IsNotEmpty()
  @MaxLength(150)
  roleTitle!: string;

  @IsOptional()
  @IsString()
  @MaxLength(150)
  company?: string;

  @IsString()
  @IsNotEmpty()
  @MaxLength(5000)
  description!: string;
}

/**
 * CREATE APPLICATION DTO
 *
 * Applicant identity must come from the authenticated JWT.
 * Never accept userId from the submitted application.
 */
export class CreateApplicationDto {
  @IsString()
  @IsNotEmpty()
  @Matches(/^[a-fA-F0-9]{24}$/, {
    message: "jobId must be a valid MongoDB ObjectId",
  })
  jobId!: string;

  @IsString()
  @IsNotEmpty()
  @Length(2, 150)
  fullName!: string;

  @IsEmail()
  @MaxLength(254)
  email!: string;

  @IsString()
  @IsNotEmpty()
  @Length(5, 30)
  phone!: string;

  @IsString()
  @IsNotEmpty()
  @MaxLength(200)
  location!: string;

  /**
   * OPTIONAL PROFILE INFORMATION
   */
  @IsOptional()
  @IsUrl(
    {
      require_protocol: true,
    },
    {
      message: "linkedInUrl must be a valid URL",
    },
  )
  @MaxLength(2048)
  linkedInUrl?: string;

  @IsOptional()
  @IsString()
  @MaxLength(255)
  resumeFileName?: string;

  /**
   * Resume URL should ideally be generated by your backend
   * after validating an uploaded file.
   */
  @IsOptional()
  @IsUrl(
    {
      require_protocol: true,
    },
    {
      message: "resumeUrl must be a valid URL",
    },
  )
  @MaxLength(2048)
  resumeUrl?: string;

  /**
   * EDUCATION
   */
  @ValidateNested()
  @Type(() => EducationDto)
  education!: EducationDto;

  /**
   * EXPERIENCE
   */
  @IsOptional()
  @ValidateNested()
  @Type(() => ExperienceDto)
  experience?: ExperienceDto;

  /**
   * SKILLS
   */
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(100)
  @IsString({ each: true })
  skills?: string[];

  /**
   * COVER LETTER
   */
  @IsOptional()
  @IsString()
  @MaxLength(10000)
  coverLetter?: string;

  /**
   * WORK AUTHORIZATION
   */
  @IsBoolean()
  workAuthorized!: boolean;

  /**
   * AVAILABILITY
   */
  @IsOptional()
  @IsDateString(
    {},
    {
      message: "availableStartDate must be a valid date",
    },
  )
  availableStartDate?: string;

  /**
   * CUSTOM APPLICATION QUESTIONS
   */
  @IsOptional()
  @IsObject()
  answers?: Record<string, string>;

  /**
   * Attach the resume stored on the applicant's career profile.
   * The server copies it privately for this application.
   */
  @IsOptional()
  @IsBoolean()
  useProfileResume?: boolean;
}
