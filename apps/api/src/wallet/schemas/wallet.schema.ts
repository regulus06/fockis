import {
  Prop,
  Schema,
  SchemaFactory,
} from "@nestjs/mongoose";

import {
  HydratedDocument,
  Types,
} from "mongoose";

/* ============================================================================
DOCUMENT TYPE
============================================================================ */

export type WalletDocument =
  HydratedDocument<Wallet>;

/* ============================================================================
WALLET
============================================================================ */

@Schema({
  timestamps: true,
})
export class Wallet {

  /* ==========================================================================
  OWNER
  ========================================================================== */

  @Prop({
    type: Types.ObjectId,
    ref: "User",
    required: true,
    unique: true,
    index: true,
  })
  userId!: Types.ObjectId;

  /* ==========================================================================
  AVAILABLE COINS
  ========================================================================== */

  @Prop({
    type: Number,
    default: 0,
    min: 0,
  })
  coins!: number;

  /* ==========================================================================
  TOTAL PURCHASED
  ========================================================================== */

  @Prop({
    type: Number,
    default: 0,
    min: 0,
  })
  totalPurchased!: number;

  /* ==========================================================================
  TOTAL SPENT
  ========================================================================== */

  @Prop({
    type: Number,
    default: 0,
    min: 0,
  })
  totalSpent!: number;

  /* ==========================================================================
  TOTAL RECEIVED
  ========================================================================== */

  @Prop({
    type: Number,
    default: 0,
    min: 0,
  })
  totalReceived!: number;

  /* ==========================================================================
  TIMESTAMPS

  Managed automatically by:
  @Schema({ timestamps: true })
  ========================================================================== */

  createdAt!: Date;

  updatedAt!: Date;
}

/* ============================================================================
SCHEMA
============================================================================ */

export const WalletSchema =
  SchemaFactory.createForClass(
    Wallet,
  );