import { Prop, Schema, SchemaFactory } from "@nestjs/mongoose";
import { HydratedDocument, Types } from "mongoose";

/* ============================================================================
   CALL RECORDS
   One document per voice/video call. Drives the ringing timeout, missed
   calls, call history, push de-duplication and LiveKit room access.
============================================================================ */

export const CALL_TYPES = ["voice", "video"] as const;
export type CallMediaType = (typeof CALL_TYPES)[number];

export const CALL_STATUSES = ["ringing", "accepted", "ended", "rejected", "missed", "canceled", "busy", "failed"] as const;
export type CallState = (typeof CALL_STATUSES)[number];

/** States in which the call is over and can no longer be answered. */
export const FINAL_CALL_STATES: CallState[] = ["ended", "rejected", "missed", "canceled", "busy", "failed"];

@Schema({ collection: "calls", timestamps: true })
export class CallRecord {
  /** Public call ID (UUID) used by sockets, push payloads and the apps. */
  @Prop({ type: String, required: true, unique: true })
  callId!: string;

  @Prop({ type: Types.ObjectId, ref: "User", required: true, index: true })
  callerId!: Types.ObjectId;

  @Prop({ type: Types.ObjectId, ref: "User", required: true, index: true })
  receiverId!: Types.ObjectId;

  @Prop({ type: String, enum: CALL_TYPES, required: true })
  type!: CallMediaType;

  @Prop({ type: String, enum: CALL_STATUSES, default: "ringing", index: true })
  status!: CallState;

  /** Ringing stops (and the call becomes "missed") at this time. */
  @Prop({ type: Date, required: true, index: true })
  ringingUntil!: Date;

  @Prop({ type: Date, default: null })
  acceptedAt?: Date | null;

  /** The device that answered (other devices stop ringing). */
  @Prop({ type: String, default: "" })
  acceptedDeviceId!: string;

  @Prop({ type: Date, default: null })
  endedAt?: Date | null;

  @Prop({ type: Types.ObjectId, ref: "User", default: null })
  endedBy?: Types.ObjectId | null;

  @Prop({ type: String, default: "" })
  endReason!: string;

  @Prop({ type: Number, default: 0 })
  durationSec!: number;

  /** LiveKit room for the media. Only the two participants get tokens. */
  @Prop({ type: String, required: true })
  roomName!: string;

  /** Device IDs already sent the incoming-call push (no duplicates). */
  @Prop({ type: [String], default: [] })
  notifiedDevices!: string[];

  /** The receiver has seen the missed call in the call history. */
  @Prop({ type: Boolean, default: false })
  missedSeen!: boolean;

  createdAt?: Date;
  updatedAt?: Date;
}

export type CallRecordDocument = HydratedDocument<CallRecord>;
export const CallRecordSchema = SchemaFactory.createForClass(CallRecord);
CallRecordSchema.index({ callerId: 1, createdAt: -1 });
CallRecordSchema.index({ receiverId: 1, createdAt: -1 });
CallRecordSchema.index({ status: 1, ringingUntil: 1 });

/* ============================================================================
   USER DEVICES (push tokens for incoming calls)
   Tokens are never returned by the API (select: false).
============================================================================ */

export const DEVICE_PLATFORMS = ["android", "ios", "web"] as const;
export type DevicePlatform = (typeof DEVICE_PLATFORMS)[number];

@Schema({ collection: "user_devices", timestamps: true })
export class UserDevice {
  @Prop({ type: Types.ObjectId, ref: "User", required: true, index: true })
  userId!: Types.ObjectId;

  /** Stable ID generated by the app on first launch. */
  @Prop({ type: String, required: true })
  deviceId!: string;

  @Prop({ type: String, enum: DEVICE_PLATFORMS, required: true })
  platform!: DevicePlatform;

  /** Firebase Cloud Messaging registration token (Android). */
  @Prop({ type: String, default: "", select: false })
  pushToken!: string;

  /** APNs PushKit VoIP token (iOS). */
  @Prop({ type: String, default: "", select: false })
  voipToken!: string;

  @Prop({ type: String, default: "" })
  deviceName!: string;

  @Prop({ type: String, default: "" })
  appVersion!: string;

  @Prop({ type: Date, default: () => new Date() })
  lastSeenAt!: Date;

  /** Set when a push service reports the token as invalid, or on sign-out. */
  @Prop({ type: Date, default: null })
  disabledAt?: Date | null;

  createdAt?: Date;
  updatedAt?: Date;
}

export type UserDeviceDocument = HydratedDocument<UserDevice>;
export const UserDeviceSchema = SchemaFactory.createForClass(UserDevice);
UserDeviceSchema.index({ userId: 1, deviceId: 1 }, { unique: true });
