import {
  IsArray,
  IsBoolean,
  IsNumber,
  IsOptional,
  IsString,
  Max,
  Min,
} from "class-validator";

/* ============================================================
   UPDATE SUBSCRIPTION PLAN DTO
============================================================ */

export class UpdateSubscriptionPlanDto {

  /* ============================================================
     DISPLAY NAME
  ============================================================ */

  @IsOptional()
  @IsString()
  name?: string;

  /* ============================================================
     DESCRIPTION
  ============================================================ */

  @IsOptional()
  @IsString()
  description?: string;

  /* ============================================================
     MONTHLY PRICE
  ============================================================ */

  @IsOptional()
  @IsNumber()
  @Min(0)
  monthlyPrice?: number;

  /* ============================================================
     YEARLY PRICE
  ============================================================ */

  @IsOptional()
  @IsNumber()
  @Min(0)
  yearlyPrice?: number;

  /* ============================================================
     CURRENCY
  ============================================================ */

  @IsOptional()
  @IsString()
  currency?: string;

  /* ============================================================
     FEATURES
  ============================================================ */

  @IsOptional()
  @IsArray()
  @IsString({
    each: true,
  })
  features?: string[];

  /* ============================================================
     ACTIVE
  ============================================================ */

  @IsOptional()
  @IsBoolean()
  active?: boolean;

  /* ============================================================
     POPULAR
  ============================================================ */

  @IsOptional()
  @IsBoolean()
  popular?: boolean;

  /* ============================================================
     DISPLAY ORDER
  ============================================================ */

  @IsOptional()
  @IsNumber()
  @Min(0)
  @Max(999)
  displayOrder?: number;

  /* ============================================================
     STRIPE MONTHLY PRICE
  ============================================================ */

  @IsOptional()
  @IsString()
  stripeMonthlyPriceId?: string;

  /* ============================================================
     STRIPE YEARLY PRICE
  ============================================================ */

  @IsOptional()
  @IsString()
  stripeYearlyPriceId?: string;
}